"""Known third-party hosting providers (CDN, cloud, SaaS), for the wildcard rule in Blueprint
§4.1: a name matched only by a wildcard must not resolve to someone else's infrastructure.

The data is a bundled snapshot (`data/providers.json`) generated by
`scripts/update_providers.py` from the providers' published lists, and reviewed in a PR when
it changes. A provider is recognized by its address ranges or by a CNAME suffix in the
resolution's chain.
"""

import bisect
import ipaddress
import json
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from functools import cache
from importlib import resources

from quiver.core.policy.resolve import IPAddress, Resolution


@dataclass(frozen=True)
class _Range:
    start: int
    end: int
    provider: str


class ProviderIndex:
    def __init__(
        self,
        networks: Mapping[str, Iterable[str]],
        cname_suffixes: Mapping[str, Iterable[str]],
        generated_at: str = "",
    ):
        self.generated_at = generated_at
        self._suffixes = [
            (suffix.lower().strip(".").removeprefix("*."), provider)
            for provider, suffixes in cname_suffixes.items()
            for suffix in suffixes
        ]
        self._ranges: dict[int, list[_Range]] = {4: [], 6: []}
        for provider, nets in networks.items():
            parsed = [ipaddress.ip_network(n) for n in nets]
            for version in (4, 6):
                for net in ipaddress.collapse_addresses(n for n in parsed if n.version == version):
                    self._ranges[version].append(
                        _Range(int(net.network_address), int(net.broadcast_address), provider)
                    )
        self._starts: dict[int, list[int]] = {}
        self._max_end: dict[int, list[int]] = {}
        for version, ranges in self._ranges.items():
            ranges.sort(key=lambda r: (r.start, r.end))
            self._starts[version] = [r.start for r in ranges]
            running, max_end = -1, []
            for r in ranges:
                running = max(running, r.end)
                max_end.append(running)
            self._max_end[version] = max_end

    @classmethod
    def from_json(cls, data: Mapping) -> "ProviderIndex":
        providers = data["providers"]
        return cls(
            {name: p.get("networks", []) for name, p in providers.items()},
            {name: p.get("cname_suffixes", []) for name, p in providers.items()},
            data.get("generated_at", ""),
        )

    def provider_of_address(self, ip: IPAddress) -> str | None:
        value, version = int(ip), ip.version
        i = bisect.bisect_right(self._starts[version], value) - 1
        # Ranges from different providers may overlap: walk back while one could still cover it.
        while i >= 0 and self._max_end[version][i] >= value:
            r = self._ranges[version][i]
            if r.start <= value <= r.end:
                return r.provider
            i -= 1
        return None

    def provider_of_name(self, name: str) -> str | None:
        name = name.lower().rstrip(".")
        for suffix, provider in self._suffixes:
            if name == suffix or name.endswith("." + suffix):
                return provider
        return None

    def classify(self, resolution: Resolution) -> str | None:
        """The provider hosting this name, if it is a known third party: by CNAME chain first
        (the most specific evidence), then by address."""
        for cname in resolution.cnames:
            provider = self.provider_of_name(cname)
            if provider:
                return provider
        for ip in resolution.addresses:
            provider = self.provider_of_address(ip)
            if provider:
                return provider
        return None


@cache
def bundled_providers() -> ProviderIndex:
    text = resources.files("quiver.core.policy").joinpath("data/providers.json").read_text()
    return ProviderIndex.from_json(json.loads(text))
